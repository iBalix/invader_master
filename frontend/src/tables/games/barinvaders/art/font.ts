const BLANK = [0, 0, 0, 0, 0, 0, 0, 0];

/** glyphe d'un caractère (majuscules, chiffres, signes de la borne) */
export function glyph(ch: string): readonly number[] {
  const d = ch.charCodeAt(0) - 48;
  if (ch.length === 1 && d >= 0 && d <= 9) return DIGIT_GLYPHS[d];
  return LETTERS[ch] ?? BLANK;
}

/**
 * Texte affichable par la police : majuscules, accents retirés, caractères
 * inconnus remplacés par une espace, longueur bornée.
 */
export function toRomText(text: string, maxLen = 32): string {
  const plain = text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
  let out = '';
  for (const ch of plain) {
    if (out.length >= maxLen) break;
    out += (ch >= '0' && ch <= '9') || LETTERS[ch] || ch === ' ' ? ch : ' ';
  }
  return out;
}

/**
 * Écrit `text` dans un tampon 224x256 (index y * 224 + x) à partir du coin
 * haut-gauche (x, y), avec la couleur de zone de chaque pixel.
 */
export function drawText(px: Uint32Array, colors: Uint32Array, text: string, x: number, y: number): void {
  for (let c = 0; c < text.length; c += 1) {
    const g = glyph(text[c]);
    for (let i = 0; i < 8; i += 1) {
      const col = x + c * 8 + i;
      if (col < 0 || col >= 224) continue;
      const v = g[i];
      if (v === 0) continue;
      for (let b = 0; b < 8; b += 1) {
        if (((v >> b) & 1) === 0) continue;
        const row = y + 7 - b;
        if (row < 0 || row >= 256) continue;
        px[row * 224 + col] = colors[row * 224 + col];
      }
    }
  }
}

/** sprite de colonnes (8 bits de haut) aux coordonnées écran, haut-gauche (x, y) */
export function drawColumns(px: Uint32Array, colors: Uint32Array, cols: readonly number[], x: number, y: number): void {
  for (let i = 0; i < cols.length; i += 1) {
    const col = x + i;
    if (col < 0 || col >= 224) continue;
    const v = cols[i];
    for (let b = 0; b < 8; b += 1) {
      if (((v >> b) & 1) === 0) continue;
      const row = y + 7 - b;
      if (row < 0 || row >= 256) continue;
      px[row * 224 + col] = colors[row * 224 + col];
    }
  }
}
